//go:build linux

package update

import (
	"debug/elf"
	"os"
	"sync"
)

// isStatic says whether this binary is statically linked, as the
// container image and Alpine package builds are: it has no program
// interpreter.
var isStatic = sync.OnceValue(func() bool {
	exe, err := os.Executable()
	if err != nil {
		return false
	}
	f, err := elf.Open(exe)
	if err != nil {
		return false
	}
	defer f.Close()
	for _, p := range f.Progs {
		if p.Type == elf.PT_INTERP {
			return false
		}
	}
	return true
})
